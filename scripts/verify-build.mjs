import { readFile, readdir, rm, stat } from 'node:fs/promises'
import { resolve, sep } from 'node:path'
import assert from 'node:assert/strict'

const root = resolve(import.meta.dirname, '..')
const dist = resolve(root, 'dist')
const originals = resolve(dist, 'portfolio')
assert.ok(originals.startsWith(`${dist}${sep}`), 'Cleanup must remain inside build output')
await rm(originals, { recursive: true, force: true })
const html = await readFile(resolve(dist, 'index.html'), 'utf8')
assert.ok(html.includes('Brindle — Property Maintenance &amp; Construction Support') || html.includes('Brindle — Property Maintenance & Construction Support'))
assert.ok(html.includes('0451 743 037'))
assert.ok(!html.includes('/src/main.tsx'))
assert.ok(html.includes('id="home-title"'), 'Homepage must be statically rendered')
assert.ok(html.includes('id="work"'), 'Portfolio must exist before JavaScript')
assert.equal((html.match(/<h1[ >]/g) || []).length, 1, 'One page title')
assert.equal((html.match(/class="project-slide /g) || []).length, 4, 'Four real-photo stages must be in static HTML')
assert.ok(html.includes('id="project-stage"'))
assert.ok(html.includes('class="project-detail"'))
assert.ok(html.indexOf('id="top"') < html.indexOf('id="work"'), 'Construction experience must open the site')
assert.ok(html.indexOf('id="services"') < html.indexOf('id="work"'), 'Varied services must lead the genuine project')
assert.equal((html.match(/class="service-tile service-tile-/g) || []).length, 7)
assert.equal((html.match(/class="imagery-disclosure"/g) || []).length, 1, 'One service-imagery disclosure')
assert.ok(!html.includes('AI-GENERATED / INSPIRATION'))
assert.ok(!html.includes('UNBUILT CONCEPT'))
assert.ok(!html.includes('Design Inspiration'))
const experience = html.slice(html.indexOf('id="experience"'), html.indexOf('id="contact"'))
assert.ok(!/images\/10000209/.test(experience), 'Do not repeat the genuine project in experience content')
assert.ok(!html.includes('will-reveal'), 'Photographs must not depend on reveal scripts')
assert.ok(!html.includes('<canvas'), 'Prerender a fallback before client WebGL starts')
const paths = [...html.matchAll(/(?:src|href)="([^"]+)"/g)].map(m => m[1]).filter(p => !p.includes(':') && !p.startsWith('#'))
for (const path of paths) {
  const localPath = /\/(assets|images)\//.test(path) ? path.slice(path.indexOf(path.includes('/assets/') ? 'assets/' : 'images/')) : path.split('/').at(-1)
  await stat(resolve(dist, localPath))
}
const images = await readdir(resolve(dist, 'images'))
assert.equal(images.filter(f => f.endsWith('.webp')).length, 18)
assert.ok(!images.some(f => /100002083[1-5]/.test(f)))
assert.ok(!(await readdir(dist)).includes('references'))
const conceptAssets = await readdir(resolve(dist, 'images/concept'))
assert.equal(conceptAssets.filter(file => file.endsWith('.webp')).length, 6)
assert.ok(!conceptAssets.some(file => /\.(jpg|png)$/.test(file)), 'Do not ship source files')
assert.ok(html.includes('Outdoor Transformation — Design Visualisation'))
assert.ok(html.includes('images/concept/patio-proposed-v2-800.webp'))
assert.ok(html.includes('images/concept/patio-existing-800.webp'))
assert.ok(html.includes('id="patio-comparison"'))
assert.equal((html.match(/class="outdoor-comparison"/g) || []).length, 1)
assert.equal((await readdir(resolve(dist, 'images/inspiration'))).filter(file => file.endsWith('.webp')).length, 21)
assert.ok(!html.includes('id="patio-grid"'), 'The broken generic concept diagram must be removed')
await stat(resolve(dist, 'robots.txt'))
await stat(resolve(dist, 'favicon.svg'))
console.log('Static output verified: full-screen opening, services first with seven varied images and one disclosure, compact genuine project, patio comparison, correct local assets and no raw originals.')
